export function youtubeWatchUrl(id: string): string {
  return `https://www.youtube.com/watch?v=${id}`;
}

export function youtubeThumbUrl(
  id: string,
  quality: 'hqdefault' | 'sddefault' | 'maxresdefault' = 'hqdefault',
): string {
  return `https://i.ytimg.com/vi/${id}/${quality}.jpg`;
}

export function youtubeHeroUrl(id: string): string {
  return youtubeThumbUrl(id, 'sddefault');
}

export function youtubeEmbedUrl(id: string): string {
  return `https://www.youtube.com/embed/${id}`;
}

export function videosByIds(ids: readonly string[]): JourneyVideo[] {
  return ids
    .map((id) => JOURNEY_VIDEOS.find((video) => video.id === id))
    .filter((video): video is JourneyVideo => video !== undefined);
}
